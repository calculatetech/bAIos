param(
    [string]$OutputDirectory = "reference/disassembly"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$reference = Join-Path $root "reference"
$output = if ([IO.Path]::IsPathRooted($OutputDirectory)) {
    $OutputDirectory
} else {
    Join-Path $root $OutputDirectory
}
$output = [IO.Path]::GetFullPath($output)
$rootPrefix = [IO.Path]::GetFullPath($root).TrimEnd('\') + '\'
if (-not $output.StartsWith($rootPrefix, [StringComparison]::OrdinalIgnoreCase)) {
    throw "OutputDirectory must resolve below $root."
}
$ndisasm = (Get-Command ndisasm -ErrorAction SilentlyContinue).Source
if (-not $ndisasm) {
    $ndisasm = Join-Path $env:LOCALAPPDATA "bin/NASM/ndisasm.exe"
}
if (-not (Test-Path -LiteralPath $ndisasm)) { throw "NDISASM was not found." }

[IO.Directory]::CreateDirectory($output) | Out-Null
$roms = @(Get-ChildItem -LiteralPath $reference -File -Filter "*.bin" | Sort-Object Name)
if ($roms.Count -eq 0) { throw "No reference ROMs were found." }

foreach ($rom in $roms) {
    if ($rom.Length -ne 0x20000) { throw "$($rom.Name) is not a 128 KiB physical ROM." }
    $hash = (Get-FileHash -Algorithm SHA256 -LiteralPath $rom.FullName).Hash
    $base = [IO.Path]::GetFileNameWithoutExtension($rom.Name)
    $header = @(
        "; Generated by tools/disassemble-references.ps1."
        "; Source: reference/$($rom.Name)"
        "; Source SHA-256: $hash"
        "; Mode: 16-bit x86. Displayed addresses are offsets within the named segment."
        ""
    )

    $c000 = Join-Path $output "$base.c000.ndisasm.txt"
    $header | Set-Content -LiteralPath $c000 -Encoding utf8
    & $ndisasm -b 16 -w -o 0 -k 65536,65536 $rom.FullName | Add-Content -LiteralPath $c000 -Encoding utf8
    if ($LASTEXITCODE -ne 0) { throw "NDISASM failed for $($rom.Name) C000 region." }

    $f000 = Join-Path $output "$base.f000.ndisasm.txt"
    $header | Set-Content -LiteralPath $f000 -Encoding utf8
    & $ndisasm -b 16 -w -o 0 -e 65536 $rom.FullName | Add-Content -LiteralPath $f000 -Encoding utf8
    if ($LASTEXITCODE -ne 0) { throw "NDISASM failed for $($rom.Name) F000 region." }
}

"Wrote $($roms.Count * 2) searchable disassemblies to $output."
